UNION ALL
SELECT 'PROC_EXISTS: SP_LOAD_DIM_CUSTOMER',
       IFF(COUNT(*) >= 1, 'PASS', 'FAIL'),
       IFF(COUNT(*) >= 1, 'Procedure exists', 'Procedure NOT found')
FROM TASTYBYTES_CONSUMPTION.INFORMATION_SCHEMA.PROCEDURES
WHERE PROCEDURE_SCHEMA = 'WAREHOUSE' AND PROCEDURE_NAME = 'SP_LOAD_DIM_CUSTOMER'

UNION ALL
SELECT 'PROC_EXISTS: SP_LOAD_FACT_ORDER_LINE',
       IFF(COUNT(*) >= 1, 'PASS', 'FAIL'),
       IFF(COUNT(*) >= 1, 'Procedure exists', 'Procedure NOT found')
FROM TASTYBYTES_CONSUMPTION.INFORMATION_SCHEMA.PROCEDURES
WHERE PROCEDURE_SCHEMA = 'WAREHOUSE' AND PROCEDURE_NAME = 'SP_LOAD_FACT_ORDER_LINE'

-- =====================================================================
-- SECTION 7: Masking Check (switch to TB_ANALYST to verify PII is masked)
-- =====================================================================

UNION ALL
SELECT 'MASKING_CHECK: STG_CUSTOMER_LOYALTY.FIRST_NAME masked for analyst',
       IFF(val = '**MASKED**', 'PASS', 'FAIL'),
       'Value seen by TB_ANALYST: ' || val
FROM (
  SELECT FIRST_NAME AS val
  FROM TASTYBYTES_REFINED.STAGING.STG_CUSTOMER_LOYALTY
  LIMIT 1
)

ORDER BY CHECK_NAME;
